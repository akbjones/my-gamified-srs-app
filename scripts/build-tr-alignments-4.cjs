// Build alignments
const alignments = {};

for (const card of data) {
  const words = card.target
    .toLowerCase()
    .replace(/[.,!?;:""«»()]/g, '')
    .split(/\s+/)
    .filter(w => w.length > 0);

  for (const word of words) {
    // Get meaning: check overrides first, then dict
    let meaning = dict[word];
    if (overrides[card.id] && overrides[card.id][word]) {
      meaning = overrides[card.id][word];
    }
    if (!meaning) {
      meaning = "MISSING";
    }

    if (!alignments[word]) {
      alignments[word] = [];
    }
    alignments[word].push({ en: meaning, card: card.id });
  }
}

// Check for MISSING
let missingCount = 0;
const missingWords = new Set();
for (const [word, entries] of Object.entries(alignments)) {
  for (const e of entries) {
    if (e.en === "MISSING") {
      missingCount++;
      missingWords.add(word);
    }
  }
}

if (missingCount > 0) {
  console.error(`WARNING: ${missingCount} MISSING translations for ${missingWords.size} words:`);
  console.error([...missingWords].sort().join(', '));
}

// Write output
const output = { alignments };
fs.writeFileSync(
  path.join(__dirname, 'output', 'tr-alignments-4.json'),
  JSON.stringify(output, null, 2),
  'utf8'
);

