// Now process all cards
const alignments = {};

function stripPunct(w) {
  return w.replace(/[.,!?;:"""«»()\u201C\u201D\u2018\u2019]/g, '').replace(/^-+|-+$/g, '');
}

function tokenize(sentence) {
  return sentence.split(/\s+/).map(w => stripPunct(w).toLowerCase()).filter(Boolean);
}

// Context-specific overrides: for certain card IDs, certain words have specific meanings
// We'll build these as we process

for (const card of cards) {
  const tokens = tokenize(card.target);
  const en = card.english;
  const id = card.id;

  for (const tok of tokens) {
    if (!alignments[tok]) alignments[tok] = [];

    // Determine meaning based on dictionary + context
    let meaning = dict[tok];

    // Context-dependent overrides
    if (!meaning) {
      meaning = inferMeaning(tok, en, card.target);
    }

    if (!meaning) meaning = "?";

    // Some words need context-dependent meanings
    meaning = contextOverride(tok, en, meaning, card.target);

    alignments[tok].push({ en: meaning, card: id });
  }
}

function inferMeaning(tok, en, tr) {
  // Try to infer from morphology

  // -de/-da/-te/-ta locative
  if (tok.endsWith('de') || tok.endsWith('da') || tok.endsWith('te') || tok.endsWith('ta')) {
    const root = tok.slice(0, -2);
    if (dict[root]) return dict[root];
  }
  // -den/-dan ablative
  if (tok.endsWith('den') || tok.endsWith('dan')) {
    const root = tok.slice(0, -3);
    if (dict[root]) return dict[root];
  }
  // -e/-a dative
  if (tok.endsWith('ya') || tok.endsWith('ye')) {
    const root = tok.slice(0, -2);
    if (dict[root]) return dict[root];
    const root2 = tok.slice(0, -1);
    if (dict[root2]) return dict[root2];
  }

  // -ler/-lar plural
  if (tok.endsWith('ler') || tok.endsWith('lar')) {
    const root = tok.slice(0, -3);
    if (dict[root]) return dict[root];
  }

  // -i/-ı/-u/-ü accusative
  if (tok.length > 3) {
    const root1 = tok.slice(0, -1);
    if (dict[root1]) return dict[root1];
  }

  // Common suffixed patterns
  if (tok.endsWith('yor') || tok.endsWith('ıyor') || tok.endsWith('iyor') || tok.endsWith('uyor') || tok.endsWith('üyor')) {
    return "?verb";
  }

  return null;
}

function contextOverride(tok, en, meaning, tr) {
  // "gelecek" can mean "next" or "to come" depending on context
  if (tok === 'gelecek') {
    // Check if it's used as "next" (gelecek hafta/ay/yıl)
    if (/gelecek\s+(hafta|ay|yıl)/i.test(tr)) return "next";
    // "Gelecek yıl" at start
    if (/^gelecek\s+yıl/i.test(tr)) return "next";
    // As a noun "future"
    if (en.includes('future')) return "future";
    // As verb "will come"
    if (en.includes('will come') || en.includes('Guests will come')) return "to come";
    if (en.includes('next')) return "next";
    return meaning;
  }

  // "o" can be he/she/it or "that"
  if (tok === 'o') {
    if (en.startsWith('He/She') || en.startsWith('He/') || en.includes('He/She')) return "he/she";
    if (en.includes('That navy')) return "that";
    return "he/she";
  }

  // "saat" = clock/hour/o'clock
  if (tok === 'saat') {
    if (en.includes("o'clock") || en.includes('half past') || en.includes('at three') || en.includes('at six') || en.includes('quarter past')) return "o'clock";
    if (en.includes('hour') || en.includes('takes')) return "hour";
    if (en.includes('time')) return "time, hour";
    return "hour, clock";
  }

  // "yol" can be road or way
  if (tok === 'yol' || tok === 'yolu') {
    if (en.includes('road')) return "road";
    if (en.includes('way')) return "way, road";
    return "road";
  }

  // "bir" = a/one
  if (tok === 'bir') {
    return "a, one";
  }

  // "açar" can be "to open"
  if (tok === 'açar') return "to open";

  // "ne" = what
  if (tok === 'ne') return "what";

  // "doğru" can be correct or towards
  if (tok === 'doğru') {
    if (en.includes('towards')) return "towards";
    if (en.includes('correct')) return "correct";
    return "correct, towards";
  }

  // "kış" vs "kışın"
  if (tok === 'kış') {
    if (en.includes('winter')) return "winter";
    return "winter";
  }

  // "yüzde" can be percent
  if (tok === 'yüzde') return "percent";

  // "içi" in "hafta içi" = weekday
  if (tok === 'içi' && tr.includes('hafta içi')) return "weekday";

  // "sonu" in "hafta sonu" = weekend
  if (tok === 'sonu' || tok === 'sonunda') {
    if (tr.includes('hafta sonu')) return "weekend";
    return "end";
  }

  // "içinde" = inside
  if (tok === 'içinde') return "inside";

  // "başı" in "kişi başı" = per person
  if (tok === 'başı') {
    if (tr.includes('kişi başı')) return "per";
    return "head, beginning";
  }

  // "var" = there is / exists
  if (tok === 'var') return "there is/are";

  // "mi/mı/mu/mü" = question particle
  if (tok === 'mi' || tok === 'mı' || tok === 'mu' || tok === 'mü') return "question particle";
  if (tok === 'mısınız' || tok === 'misiniz' || tok === 'musunuz' || tok === 'müsünüz') return "question particle";
  if (tok === 'mısın' || tok === 'misin' || tok === 'musun' || tok === 'müsün') return "question particle";

  // "açıkta" = off/away (in sea context) vs open
  if (tok === 'açıkta') {
    if (en.includes('off the coast')) return "off, away";
    return "open, off";
  }

  // "yağar" = to rain/snow
  if (tok === 'yağar') return "to rain/snow";

  return meaning;
}

