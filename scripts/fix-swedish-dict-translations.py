def main():
    with open(SV_TS, 'r', encoding='utf-8') as f:
        content = f.read()

    # Find all dictionary entries
    pattern = r"'([^']+)':\s*\{\s*en:\s*'([^']+)'\s*,\s*ipa:\s*'([^']+)'\s*,\s*pos:\s*'([^']+)'\s*\}"
    matches = re.findall(pattern, content)

    total = len(matches)
    self_translated_before = sum(1 for k, e, _, _ in matches if k.lower() == e.lower())

    print(f"Total entries: {total}")
    print(f"Self-translated before: {self_translated_before} ({self_translated_before*100//total}%)")

    # Track what we fix
    fixed = 0
    kept = 0
    missing = []

    for key, en, ipa, pos in matches:
        if key.lower() != en.lower():
            continue  # Already has a different translation

        key_lower = key.lower()

        if key_lower in KEEP_AS_IS:
            kept += 1
            continue

        if key_lower in TRANSLATIONS:
            new_en = TRANSLATIONS[key_lower]
            # Escape single quotes in the new translation
            new_en_escaped = new_en.replace("'", "\\'")
            old = f"'{key}': {{ en: '{en}', ipa: '{ipa}', pos: '{pos}' }}"
            new = f"'{key}': {{ en: '{new_en_escaped}', ipa: '{ipa}', pos: '{pos}' }}"
            content = content.replace(old, new)
            fixed += 1
        else:
            missing.append(key)

    # Write back
    with open(SV_TS, 'w', encoding='utf-8') as f:
        f.write(content)

    # Re-count self-translated
    matches_after = re.findall(pattern, content)
    self_translated_after = sum(1 for k, e, _, _ in matches_after if k.lower() == e.lower())

    print(f"\nFixed: {fixed}")
    print(f"Kept as-is (legitimate): {kept}")
    print(f"Missing translations: {len(missing)}")
    print(f"\nSelf-translated after: {self_translated_after} ({self_translated_after*100//len(matches_after)}%)")

    if missing:
        print(f"\n--- Missing translations ({len(missing)}) ---")
        for m in sorted(missing):
            print(f"  {m}")


if __name__ == '__main__':
    main()
