// Process all cards
const alignments = {};

for (const card of cards) {
  const rawWords = card.target.replace(/[.,!?;:""«»()\-–—]/g, ' ').split(/\s+/).filter(Boolean);
  const words = rawWords.map(w => turkishLower(stripPunct(w))).filter(Boolean);

  for (const word of words) {
    if (!word) continue;
    if (!alignments[word]) alignments[word] = [];

    let meaning = dict[word] || null;

    if (meaning) {
      alignments[word].push({ en: meaning, card: card.id });
    } else {
      // Try without trailing apostrophe-suffix
      const apos = word.indexOf("'");
      if (apos > 0) {
        const root = word.substring(0, apos);
        meaning = dict[root];
        if (meaning) {
          alignments[word].push({ en: meaning, card: card.id });
          continue;
        }
      }
      // Mark as unknown - push with null so we can count
      alignments[word].push({ en: "?", card: card.id });
    }
  }
}

// Report
const totalEntries = Object.values(alignments).reduce((s, a) => s + a.length, 0);
const unknowns = {};
for (const [word, entries] of Object.entries(alignments)) {
  for (const e of entries) {
    if (e.en === "?") {
      unknowns[word] = (unknowns[word] || 0) + 1;
    }
  }
}

console.log('Total unique words:', Object.keys(alignments).length);
console.log('Total entries:', totalEntries);
console.log('Unknown words:', Object.keys(unknowns).length);
if (Object.keys(unknowns).length > 0) {
  const sorted = Object.entries(unknowns).sort((a,b) => b[1] - a[1]);
  for (const [w, c] of sorted) {
    console.log(`  ${w} (${c})`);
  }
}

// Write output
const output = { alignments };
fs.writeFileSync(
  path.join(__dirname, 'output/tr-alignments-3.json'),
  JSON.stringify(output, null, 2),
  'utf8'
);
