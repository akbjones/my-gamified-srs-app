/**
 * Generate word-level alignments for Russian flashcards.
 * For each clean card, tokenize the Russian sentence and map each word
 * to its English meaning using the card's English translation as guide.
 *
 * Output: scripts/output/ru-alignments.json
 */

const fs = require('fs');
const path = require('path');

const BASE = path.resolve(__dirname, '..');
const deck = require(path.join(BASE, 'src/data/russian/deck.json'));
const validation = require(path.join(BASE, 'scripts/output/ru-card-validation.json'));

// Build set of IDs to exclude (GARBAGE + MISMATCH)
const excludeIds = new Set(
  validation.flagged
    .filter(f => f.category === 'GARBAGE' || f.category === 'MISMATCH')
    .map(f => f.id)
);

console.log(`Deck: ${deck.length} cards, excluding ${excludeIds.size} (GARBAGE+MISMATCH)`);

// Clean cards
const cleanCards = deck.filter(c => !excludeIds.has(c.id));
console.log(`Clean cards: ${cleanCards.length}`);

// Tokenize Russian sentence: lowercase, strip punctuation, split on whitespace
function tokenize(sentence) {
  return sentence
    .replace(/[.,!?;:«»""''…––\-\(\)\[\]\/\d]/g, ' ')
    .toLowerCase()
    .split(/\s+/)
    .filter(w => w.length > 0);
}

