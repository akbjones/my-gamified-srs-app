function tokenizeEnglish(sentence) {
  return sentence
    .replace(/[.,!?;:"""''…––\-\(\)\[\]\/]/g, ' ')
    .toLowerCase()
    .split(/\s+/)
    .filter(w => w.length > 1 && !enStopWords.has(w));
}

// Build reverse index: English meaning -> set of Russian words that produce it
function buildEnRuMap() {
  const map = {};
  for (const [ru, en] of Object.entries(wordDict)) {
    const meanings = en.toLowerCase().split('/');
    for (const m of meanings) {
      const clean = m.replace(/\(.*?\)/g, '').trim();
      if (clean.startsWith('to ')) {
        const verb = clean.slice(3);
        if (!map[verb]) map[verb] = new Set();
        map[verb].add(ru);
      }
      if (!map[clean]) map[clean] = new Set();
      map[clean].add(ru);
    }
  }
  return map;
}

const enRuMap = buildEnRuMap();

function guessFromCardContext(unknownRuWords, knownMeanings, enSentence) {
  // Get English content words not yet accounted for
  const enTokens = tokenizeEnglish(enSentence);
  const coveredEn = new Set();

  // Mark which English words are covered by known Russian meanings
  for (const meaning of knownMeanings) {
    const meaningWords = meaning.toLowerCase().split(/[\s\/]+/);
    for (const mw of meaningWords) {
      const clean = mw.replace(/[()]/g, '').trim();
      if (clean.length > 1) coveredEn.add(clean);
    }
  }

  // Uncovered English content words
  const uncoveredEn = enTokens.filter(w => !coveredEn.has(w));

  // If we have exactly 1 unknown RU word and some uncovered EN words, assign them
  const result = {};
  if (unknownRuWords.length === 1 && uncoveredEn.length > 0) {
    // Assign the uncovered English words as the meaning
    const meaning = uncoveredEn.slice(0, 3).join(' ');
    result[unknownRuWords[0]] = meaning;
  } else if (unknownRuWords.length > 0 && uncoveredEn.length > 0) {
    // Multiple unknowns: try positional alignment (RU word position ~ EN word position)
    const ruPositions = unknownRuWords.map((w, i) => i);
    const enPositions = uncoveredEn.map((w, i) => i);

    if (unknownRuWords.length <= uncoveredEn.length) {
      // Assign proportionally
      for (let i = 0; i < unknownRuWords.length; i++) {
        const enIdx = Math.round(i * (uncoveredEn.length - 1) / Math.max(unknownRuWords.length - 1, 1));
        result[unknownRuWords[i]] = uncoveredEn[enIdx];
      }
    } else {
      // More unknowns than English words: assign what we can
      for (let i = 0; i < Math.min(unknownRuWords.length, uncoveredEn.length); i++) {
        result[unknownRuWords[i]] = uncoveredEn[i];
      }
    }
  }
  return result;
}

// ========== MAIN PROCESSING (TWO-PASS) ==========

const alignments = {};
let unmatchedWords = new Set();
let totalTokens = 0;
let matchedTokens = 0;

for (const card of cleanCards) {
  const tokens = tokenize(card.target);

  // Pass 1: resolve all words we can via dictionary/morphology
  const resolved = []; // {token, meaning} or {token, meaning: null}
  for (const token of tokens) {
    totalTokens++;
    const meaning = morphLookup(token);
    resolved.push({ token, meaning });
  }

  // Pass 2: for unresolved, use card-level English alignment
  const unknownTokens = resolved.filter(r => !r.meaning).map(r => r.token);
  const knownMeanings = resolved.filter(r => r.meaning).map(r => r.meaning);

  let contextGuesses = {};
  if (unknownTokens.length > 0) {
    contextGuesses = guessFromCardContext(unknownTokens, knownMeanings, card.english);
  }

  // Write results
  for (const { token, meaning } of resolved) {
    let finalMeaning = meaning || contextGuesses[token] || null;

    if (finalMeaning) {
      matchedTokens++;
    } else {
      unmatchedWords.add(token);
    }

    if (!alignments[token]) {
      alignments[token] = [];
    }

    alignments[token].push({
      en: finalMeaning || '?',
      card: card.id
    });
  }
}

