// ========== MORPHOLOGICAL STEMMER ==========
// Strip common Russian suffixes/prefixes to find stems in the dictionary

function morphLookup(word) {
  // 1. Direct lookup
  if (wordDict[word]) return wordDict[word];

  // 2. ё/е substitution
  if (word.includes('ё') && wordDict[word.replace(/ё/g, 'е')]) return wordDict[word.replace(/ё/g, 'е')];
  if (word.includes('е')) {
    const eWord = word.replace(/е/g, 'ё');
    if (wordDict[eWord]) return wordDict[eWord];
  }

  // 3. Capitalized (proper noun)
  const cap = word.charAt(0).toUpperCase() + word.slice(1);
  if (wordDict[cap]) return wordDict[cap];

  // 4. Strip common case endings and try stems
  const caseSuffixes = [
    // Long endings first
    'ениям', 'ениях', 'ениями', 'ений',
    'ами', 'ями', 'ому', 'ого', 'ыми', 'ими',
    'ённый', 'ённая', 'ённое', 'ённые', 'анный', 'анная', 'анное', 'анные',
    'ённых', 'ённым', 'анных', 'анным',
    'ённом', 'анном', 'ённой', 'анной',
    'ённую', 'анную',
    'вший', 'вшая', 'вшее', 'вшие', 'вшей', 'вшим', 'вших',
    'щий', 'щая', 'щее', 'щие', 'щей', 'щим', 'щих', 'щую',
    'ённо', 'анно',
    'ах', 'ях', 'ом', 'ем', 'ём', 'ой', 'ей', 'ёй',
    'ов', 'ев', 'ёв', 'ий', 'ый', 'ая', 'яя', 'ое', 'ее', 'ие', 'ые',
    'ую', 'юю',
    'ам', 'ям',
    'у', 'ю', 'а', 'я', 'е', 'и', 'ы', 'о'
  ];

  for (const suffix of caseSuffixes) {
    if (word.length > suffix.length + 2 && word.endsWith(suffix)) {
      const stem = word.slice(0, -suffix.length);
      // Try stem + common nominative endings
      for (const nomEnd of ['', 'а', 'о', 'е', 'ь', 'й', 'я', 'ие', 'ые', 'ка', 'ок', 'ец',
                             'ый', 'ая', 'ое', 'ие', 'ой', 'ая', 'ик', 'ник', 'ение', 'ность']) {
        const candidate = stem + nomEnd;
        if (wordDict[candidate]) return wordDict[candidate];
        const capCand = candidate.charAt(0).toUpperCase() + candidate.slice(1);
        if (wordDict[capCand]) return wordDict[capCand];
      }
      // Also try with consonant mutations (к->ч, г->ж, х->ш, т->ч, д->ж, ст->щ)
      if (stem.length > 0) {
        const lastChar = stem[stem.length - 1];
        const mutations = {'ч':'к', 'ж':'г', 'ш':'х', 'щ':'ст', 'ж':'д'};
        if (mutations[lastChar]) {
          const mutStem = stem.slice(0, -1) + mutations[lastChar];
          for (const nomEnd of ['', 'а', 'о', 'е', 'ь', 'й', 'ый', 'ая', 'ое']) {
            const candidate = mutStem + nomEnd;
            if (wordDict[candidate]) return wordDict[candidate];
          }
        }
      }
    }
  }

  // 5. Verb: strip reflexive -ся/-сь and retry
  if (word.endsWith('ся') || word.endsWith('сь')) {
    const base = word.replace(/(ся|сь)$/, '');
    if (wordDict[base]) return wordDict[base];
    const refl = morphLookupNoReflexive(base);
    if (refl) return refl;
    // Also try stripping verb endings from base
    for (const vEnd of ['ет', 'ит', 'ют', 'ят', 'ут', 'ат', 'ал', 'ала', 'али',
                         'ил', 'ила', 'или', 'ел', 'ела', 'ели']) {
      if (base.endsWith(vEnd) && base.length > vEnd.length + 2) {
        const vStem = base.slice(0, -vEnd.length);
        for (const inf of ['ать', 'ить', 'еть', 'ять', 'уть', 'овать', 'евать', 'ывать', 'ивать']) {
          if (wordDict[vStem + inf]) return wordDict[vStem + inf];
        }
      }
    }
  }

  // 6. Verb prefixes
  const verbPrefixes = ['пере', 'при', 'пре', 'раз', 'рас', 'под', 'над', 'пред', 'про', 'по', 'вы', 'за', 'на', 'от', 'об', 'до', 'из', 'со', 'у', 'в', 'с'];
  for (const prefix of verbPrefixes) {
    if (word.startsWith(prefix) && word.length > prefix.length + 2) {
      const stripped = word.slice(prefix.length);
      if (wordDict[stripped]) return wordDict[stripped];
      // Try stripping + morphLookup on the remainder
      for (const suffix of caseSuffixes.slice(0, 20)) {
        if (stripped.length > suffix.length + 2 && stripped.endsWith(suffix)) {
          const innerStem = stripped.slice(0, -suffix.length);
          for (const nomEnd of ['', 'а', 'о', 'е', 'ь', 'ать', 'ить', 'еть', 'ять', 'ый', 'ая', 'ое']) {
            if (wordDict[innerStem + nomEnd]) return wordDict[innerStem + nomEnd];
          }
        }
      }
    }
  }

  // 7. Try prefix+reflexive combo
  if (word.endsWith('ся') || word.endsWith('сь')) {
    const base = word.replace(/(ся|сь)$/, '');
    for (const prefix of verbPrefixes) {
      if (base.startsWith(prefix) && base.length > prefix.length + 2) {
        const stripped = base.slice(prefix.length);
        if (wordDict[stripped]) return wordDict[stripped];
        if (wordDict[stripped + 'ть']) return wordDict[stripped + 'ть'];
        if (wordDict[stripped + 'ться']) return wordDict[stripped + 'ться'];
      }
    }
  }

  return null;
}

function morphLookupNoReflexive(word) {
  if (wordDict[word]) return wordDict[word];
  // ё/е
  if (word.includes('ё') && wordDict[word.replace(/ё/g, 'е')]) return wordDict[word.replace(/ё/g, 'е')];
  if (word.includes('е')) {
    const eWord = word.replace(/е/g, 'ё');
    if (wordDict[eWord]) return wordDict[eWord];
  }
  return null;
}

