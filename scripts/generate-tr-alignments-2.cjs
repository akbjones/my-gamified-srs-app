// Process all cards
const alignments = {};

for (const card of cards) {
  const words = tokenize(card.target);

  for (const word of words) {
    if (!alignments[word]) {
      alignments[word] = [];
    }

    let meaning = dict[word] || "UNKNOWN";

    alignments[word].push({ en: meaning, card: card.id });
  }
}

// Output stats
let unknown = 0;
let total = 0;
const unknownWords = {};
for (const [w, arr] of Object.entries(alignments)) {
  for (const entry of arr) {
    total++;
    if (entry.en === 'UNKNOWN') {
      unknown++;
      if (!unknownWords[w]) unknownWords[w] = [];
      unknownWords[w].push(entry.card);
    }
  }
}

console.log('Total word occurrences:', total);
console.log('Unknown:', unknown);

if (unknown > 0) {
  const sortedUnknown = Object.entries(unknownWords).sort((a,b) => b[1].length - a[1].length);
  console.log('\nUnknown words (' + sortedUnknown.length + ' unique):');
  for (const [w, cards] of sortedUnknown) {
    console.log(w, cards.length, '- cards:', cards.join(', '));
  }
}

