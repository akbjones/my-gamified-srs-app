console.log(`Matched: ${matchedTokens} (${(matchedTokens/totalTokens*100).toFixed(1)}%)`);
console.log(`Unique words: ${Object.keys(alignments).length}`);
console.log(`Unmatched unique words: ${unmatchedWords.size}`);

if (unmatchedWords.size > 0) {
  const sorted = [...unmatchedWords].sort();
  console.log(`\nFirst 50 unmatched:`);
  console.log(sorted.slice(0, 50).join(', '));
}

