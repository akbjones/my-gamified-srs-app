// ── Tokenize Hindi sentence ─────────────────────────────────
function tokenize(sentence) {
  // Strip punctuation: ।, ?, !, comma, semicolon, colon, quotes, parens, dashes, ellipsis, Devanagari danda
  const cleaned = sentence
    .replace(/[।?!,;:\-\–\—\"\'\"\"''()…।॥\u0964\u0965]/g, ' ')
    .replace(/\s+/g, ' ')
    .trim();
  if (!cleaned) return [];
  return cleaned.split(' ').filter(w => w.length > 0);
}

// ── Lookup meaning for a Hindi word ─────────────────────────
function lookupMeaning(word) {
  // 1. Check fallback map first (more curated meanings)
  if (fallback[word]) return fallback[word];

  // 2. Check extra dictionary
  if (extraDict[word]) return extraDict[word];

  // 3. Check dictionary
  if (dictMap[word]) {
    let meaning = dictMap[word];
    // Truncate overly long dictionary entries
    if (meaning.length > 40) {
      meaning = meaning.split(',')[0].trim();
    }
    // For entries like "oblique plural of X" or "direct feminine of X", simplify
    if (meaning.startsWith('direct/oblique')) {
      const lemmaMatch = dictSrc.match(new RegExp(`'${word.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}'\\s*:\\s*\\{[^}]*lemma\\s*:\\s*'([^']+)'`));
      if (lemmaMatch && dictMap[lemmaMatch[1]]) {
        meaning = dictMap[lemmaMatch[1]] + ' (inflected)';
      }
    }
    return meaning;
  }

  // 4. Try without nuqta (dots under letters)
  const noNuqta = word
    .replace(/\u093C/g, '') // Remove nukta
    .replace('ज़', 'ज').replace('फ़', 'फ').replace('ख़', 'ख')
    .replace('ग़', 'ग').replace('ड़', 'ड').replace('ढ़', 'ढ');
  if (noNuqta !== word) {
    if (fallback[noNuqta]) return fallback[noNuqta];
    if (extraDict[noNuqta]) return extraDict[noNuqta];
    if (dictMap[noNuqta]) return dictMap[noNuqta];
  }

  // 5. Try with nuqta variants
  const withNuqta = word
    .replace('ज', 'ज़').replace('फ', 'फ़').replace('ख', 'ख़');
  if (withNuqta !== word) {
    if (fallback[withNuqta]) return fallback[withNuqta];
    if (extraDict[withNuqta]) return extraDict[withNuqta];
    if (dictMap[withNuqta]) return dictMap[withNuqta];
  }

  return null;
}

// ── Process all cards ───────────────────────────────────────
const alignments = {};
let totalTokens = 0;
let matchedTokens = 0;
let unmatchedWords = new Set();

for (const card of deck) {
  const tokens = tokenize(card.target);
  totalTokens += tokens.length;

  for (const token of tokens) {
    const meaning = lookupMeaning(token);
    if (!alignments[token]) {
      alignments[token] = [];
    }

    if (meaning) {
      matchedTokens++;
      alignments[token].push({ en: meaning, card: card.id });
    } else {
      unmatchedWords.add(token);
      alignments[token].push({ en: '?', card: card.id });
    }
  }
}

