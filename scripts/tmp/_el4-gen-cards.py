def build(rows, start):
    out = []
    for i, (t, e, tags, g) in enumerate(rows):
        n = start + i
        node = "node-27" if n <= 3175 else "node-28"
        card = {"id": f"el-{n}", "target": t, "english": e,
                "audio": f"el-el-{n}.mp3", "tags": tags,
                "grammarNode": node, "priority": n}
        if g:
            card["grammar"] = g
        out.append(card)
    return out

