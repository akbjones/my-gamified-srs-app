import { conjugate } from '../../src/data/conjugation/el';
const cands = [
  'ξεπερνάω','υπερβάλλω','απομονώνω','ανήκω','αποκλείω','απολαμβάνω','ενδιαφέρω',
  'ρισκάρω','σέβομαι','παραδέχομαι','πείθω','υποχωρώ','κρίνω','μπερδεύω','υπολογίζω',
  'προσαρμόζομαι','ειδοποιώ','ρυπαίνω','γλιτώνω','ξεχωρίζω','δηλώνω','αποφασίζω',
  'ωφελούμαι','αποδεικνύω','λύνομαι','βιάζομαι','απέχω','συνοψίζω','ντύνομαι',
];
for (const v of cands) {
  const t = conjugate(v);
  if (!t) { console.log(v.padEnd(16), 'NULL'); continue; }
  const g = (k: string) => (t.tenses[k] ?? []).join(' ');
  console.log(v.padEnd(16),
    '| PRES', g('Ενεστώτας (Present)'),
    '| IMPF', g('Παρατατικός (Imperfect)'),
    '| AOR', g('Αόριστος (Past)'),
    '| FUT', g('Μέλλοντας (Future)'));
}
