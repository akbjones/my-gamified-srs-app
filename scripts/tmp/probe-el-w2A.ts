/** Probe: which aorists/imperfects does the engine actually derive? */
import { conjugate, findInfinitive } from '../../src/data/conjugation/el';

const lemmas = [
  // regular -ω sigmatic candidates
  'γράφω','ανοίγω','κλείνω','νιώθω','ψάχνω','δείχνω','αρχίζω','διαβάζω',
  'αγοράζω','νομίζω','γυρίζω','ετοιμάζω','καθαρίζω','ψωνίζω','δοκιμάζω',
  'κοστίζω','συνεχίζω','πληρώνω','τελειώνω','οργανώνω','φτάνω','φτιάχνω',
  'τρέχω','προσέχω','δουλεύω','μαγειρεύω','χορεύω','ταξιδεύω','πιστεύω',
  // -άω
  'μιλάω','ρωτάω','ζητάω','πουλάω','σταματάω','ξεκινάω','βοηθάω','κρατάω',
  'μετράω','τραγουδάω','ξυπνάω','προτιμάω','απαντάω','αγαπάω',
  // B -ώ
  'ευχαριστώ','οδηγώ','τηλεφωνώ','αργώ',
  // deponent
  'σκέφτομαι','χρειάζομαι','εργάζομαι','ετοιμάζομαι','ονομάζομαι',
  // new-verb candidates
  'χάνω','κερδίζω','διαλέγω','γνωρίζω','σπουδάζω','μετακομίζω','κολυμπάω','καπνίζω','αγκαλιάζω',
  // irregulars (sanity)
  'πάω','λέω','τρώω','βλέπω','πίνω','έρχομαι','παίρνω','δίνω','μένω','στέλνω',
  'φεύγω','βρίσκω','κάνω','θέλω','μπορώ','γίνομαι','περιμένω','καταλαβαίνω',
  'μαθαίνω','πέφτω','αφήνω','φέρνω','βάζω','βγαίνω','μπαίνω','γελάω','περνάω',
  'ξεχνάω','κοιμάμαι','θυμάμαι','φοβάμαι','ακούω','είμαι','έχω','ξέρω','πηγαίνω',
];

for (const l of lemmas) {
  const t = conjugate(l);
  if (!t) { console.log(`${l}: NO TABLE`); continue; }
  const ao = t.tenses['Αόριστος (Past)'];
  const im = t.tenses['Παρατατικός (Imperfect)'];
  console.log(`${l}: AOR=${ao ? ao.join(' ') : '—'} | IMP=${im ? im.join(' ') : '—'}`);
}

