def build(entries, start_id, node):
    out = []
    for i, (t, e, extra, g) in enumerate(entries):
        n = start_id + i
        tags = ["general"]
        if extra:
            tags += [x for x in extra.split(",") if x]
        tags = boost(t, tags)
        if n in FAMILY_IDS and "family" not in tags:
            tags.append("family")
        if n in TRAVEL_IDS and "travel" not in tags:
            tags.append("travel")
        if not g and n in TIPS_EXTRA:
            g = TIPS_EXTRA[n]
        card = {
            "id": f"el-{n}",
            "target": t,
            "english": e,
            "audio": f"el-el-{n}.mp3",
            "tags": tags,
            "grammarNode": node,
            "priority": n,
        }
        if g:
            card["grammar"] = g
        out.append(card)
    return out

