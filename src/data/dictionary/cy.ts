function clean(w: string): string {
  return w.toLowerCase().replace(/[¿¡.,!?;:"""\u2018\u2019()—–«»\d/]/g, '').trim();
}

export function lookupWord(raw: string): DictEntry | null {
  const w = clean(raw);
  if (!w) return null;
  if (dict[w]) return dict[w];

  // Try removing common prefixes/mutations
  // Soft mutation reverse: try adding back original consonant
  const softReverse: Record<string, string[]> = {
    'g': ['c'], 'b': ['p'], 'd': ['t'], 'f': ['b', 'm'], 'dd': ['d'], 'l': ['ll'], 'r': ['rh'],
  };
  for (const [mut, originals] of Object.entries(softReverse)) {
    if (w.startsWith(mut)) {
      for (const orig of originals) {
        const candidate = orig + w.slice(mut.length);
        if (dict[candidate]) return dict[candidate];
      }
    }
  }

  // Try without leading mutation (g drops in soft mutation)
  if (w.length > 2) {
    // If word starts with vowel, try adding 'g' back (g drops in soft mutation)
    if ('aeiouwyâêîôûŵŷ'.includes(w[0])) {
      const candidate = 'g' + w;
      if (dict[candidate]) return dict[candidate];
    }
  }

  // Try stripping common suffixes
  for (const suf of ['au', 'iau', 'oedd', 'od', 'ion', 'ydd', 'wr', 'wyr', 'es', 'eg', 'ach', 'af']) {
    if (w.endsWith(suf) && w.length > suf.length + 2) {
      const base = w.slice(0, -suf.length);
      if (dict[base]) return dict[base];
    }
  }

  // Try removing 'r/y/n at start (contractions like mae'r → mae + y)
  if (w.includes("'")) {
    const parts = w.split("'");
    if (dict[parts[0]]) return dict[parts[0]];
  }

  return null;
}
