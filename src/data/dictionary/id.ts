const clean = (w: string) => w.toLowerCase().replace(/[^a-z-]/g, '');

export function lookupWord(word: string): DictEntry | null {
  if (!word) return null;
  const w = clean(word);
  if (!w) return null;
  if (DICT[w]) return DICT[w];
  // Derived verb form → root entry (menulis/ditulis/tertulis → tulis)
  const root = findInfinitive(w);
  if (root && DICT[root]) {
    const e = DICT[root];
    return { ...e, lemma: e.lemma ?? root };
  }
  // -nya possessive/definite clitic on nouns (istrinya → istri),
  // and -lah/-kah emphasis/question clitics
  for (const clitic of ['nya', 'lah', 'kah']) {
    if (w.endsWith(clitic) && w.length > clitic.length + 2) {
      const base = w.slice(0, -clitic.length);
      if (DICT[base]) return DICT[base];
    }
  }
  return null;
}
