function cleanWord(word: string): string {
  return word
    .replace(/[.,!?;:"""''«»()—–\-…\d]/g, '')
    .trim()
    .toLowerCase();
}

export function lookupWord(word: string): DictEntry | null {
  const clean = cleanWord(word).trim();
  if (!clean) return null;

  // Direct lookup
  if (dictionary[clean]) return dictionary[clean];

  // Try ё/е variation (ё is often written as е in informal text)
  const withYo = clean.replace(/е/g, 'ё');
  if (withYo !== clean && dictionary[withYo]) return dictionary[withYo];
  const withoutYo = clean.replace(/ё/g, 'е');
  if (withoutYo !== clean && dictionary[withoutYo]) return dictionary[withoutYo];

  // Try verb form resolution via conjugation engine
  const inf = findInfinitive(clean);
  if (inf && dictionary[inf]) return dictionary[inf];

  // Try adjective ending stripping
  for (const { suffix, bases } of ADJ_ENDINGS) {
    if (clean.endsWith(suffix) && clean.length > suffix.length + 1) {
      const stem = clean.slice(0, -suffix.length);
      for (const base of bases) {
        const candidate = stem + base;
        if (dictionary[candidate]) return dictionary[candidate];
      }
    }
  }

  // Try noun case ending stripping (longest suffix first for greedy match)
  for (const ending of NOUN_ENDINGS) {
    if (clean.endsWith(ending) && clean.length > ending.length + 1) {
      const stem = clean.slice(0, -ending.length);
      // Try direct stem
      if (dictionary[stem]) return dictionary[stem];
      // Try stem + common nominative endings
      for (const nom of ['', 'а', 'о', 'е', 'ь', 'й', 'я']) {
        const candidate = stem + nom;
        if (dictionary[candidate]) return dictionary[candidate];
      }
    }
  }

  // Try multi-word expressions
  const parts = clean.split(/\s+/);
  if (parts.length > 1) {
    // First try the whole phrase
    const phrase = parts.join(' ');
    if (dictionary[phrase]) return dictionary[phrase];
    // Then try individual words
    for (const part of parts) {
      if (dictionary[part]) return dictionary[part];
    }
  }

  // Try stripping reflexive suffix -ся/-сь
  if (clean.endsWith('ся')) {
    const base = clean.slice(0, -2);
    if (dictionary[base]) return dictionary[base];
    const infRefl = findInfinitive(clean);
    if (infRefl && dictionary[infRefl]) return dictionary[infRefl];
  }
  if (clean.endsWith('сь')) {
    const base = clean.slice(0, -2) + 'ся';
    if (dictionary[base]) return dictionary[base];
  }

  return null;
}

export default dictionary;
