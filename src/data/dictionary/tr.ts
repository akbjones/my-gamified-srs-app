// ── Turkish suffix stripping ──────────────────────────────────
// Turkish is agglutinative; words carry many suffixes for case, plural, possessive, etc.
// We try stripping common suffixes from longest to shortest.
const CASE_SUFFIXES = [
  // Plural + case (longest first)
  'lardan', 'lerden',
  'larda', 'lerde', 'lara', 'lere',
  'ları', 'leri', 'ların', 'lerin',
  // Plural
  'lar', 'ler',
  // Case suffixes (with consonant harmony variants)
  'dan', 'den', 'tan', 'ten',
  'da', 'de', 'ta', 'te',
  'ya', 'ye',
  'nı', 'ni', 'nu', 'nü',
  'ın', 'in', 'un', 'ün',
  // Possessive
  'ım', 'im', 'um', 'üm',
  'ımız', 'imiz', 'umuz', 'ümüz',
  'ınız', 'iniz', 'unuz', 'ünüz',
  // Accusative
  'ı', 'i', 'u', 'ü',
  // Dative (single vowel)
  'a', 'e',
];

// Consonant mutation: final consonants can change when a vowel suffix is added
// k→ğ, p→b, t→d, ç→c
const CONSONANT_MUTATIONS: Record<string, string> = {
  'ğ': 'k',  // kitabı → kitap: when we strip suffix, we reverse mutation
  'b': 'p',
  'd': 't',
  'c': 'ç',
};

function cleanWord(word: string): string {
  return word
    .replace(/[.,!?;:"""''()—–\-…«»]/g, '')
    .trim()
    .toLowerCase();
}

export function lookupWord(word: string): DictEntry | null {
  const clean = cleanWord(word);
  if (!clean) return null;

  // Direct lookup
  if (dictionary[clean]) return dictionary[clean];

  // Try suffix stripping (longest suffixes first — array is already ordered)
  for (const suffix of CASE_SUFFIXES) {
    if (clean.endsWith(suffix) && clean.length > suffix.length + 1) {
      const stem = clean.slice(0, -suffix.length);
      if (dictionary[stem]) return dictionary[stem];

      // Try consonant mutation reversal on the last char of stem
      // e.g., kitabı → stem "kitab" → try "kitap" (b→p)
      const lastChar = stem[stem.length - 1];
      if (CONSONANT_MUTATIONS[lastChar]) {
        const mutated = stem.slice(0, -1) + CONSONANT_MUTATIONS[lastChar];
        if (dictionary[mutated]) return dictionary[mutated];
      }

      // Try buffer consonant removal
      // When a word ends in a vowel and takes a vowel suffix, buffer 'y', 'n', 's' may appear
      if ('yns'.includes(stem[stem.length - 1]) && stem.length > 2) {
        const withoutBuffer = stem.slice(0, -1);
        if (dictionary[withoutBuffer]) return dictionary[withoutBuffer];
      }
    }
  }

  // Try using the conjugation engine's findInfinitive for verb forms
  const inf = findInfinitive(clean);
  if (inf && dictionary[inf]) return dictionary[inf];

  // Try multi-word lookups (for compound verbs like "yardım etmek")
  const parts = clean.split(/\s+/);
  if (parts.length > 1) {
    for (const part of parts) {
      if (dictionary[part]) return dictionary[part];
    }
    // Try verb forms in compound
    for (const part of parts) {
      const partInf = findInfinitive(part);
      if (partInf && dictionary[partInf]) return dictionary[partInf];
    }
  }

  // Try removing negative marker -me-/-ma- from verb forms
  // e.g., gelmiyor → gel + mi + yor → try gelmek
  const negMarkers = ['mı', 'mi', 'mu', 'mü', 'ma', 'me'];
  for (const neg of negMarkers) {
    const idx = clean.indexOf(neg);
    if (idx > 1) {
      const stem = clean.slice(0, idx);
      const ending = isBackVowelWord(stem) ? 'mak' : 'mek';
      if (dictionary[stem + ending]) return dictionary[stem + ending];
    }
  }

  return null;
}

// Helper to check if a word's last vowel is a back vowel
function isBackVowelWord(word: string): boolean {
  const backVowels = new Set('aıou');
  for (let i = word.length - 1; i >= 0; i--) {
    if (backVowels.has(word[i]) || 'eiöü'.includes(word[i])) {
      return backVowels.has(word[i]);
    }
  }
  return true; // default
}

